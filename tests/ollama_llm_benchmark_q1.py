#!/usr/bin/env python3

"""
Ollama LLM Benchmark for IEEE Access evaluation

Metrics:
- Time To First Token (TTFT)
- Total latency
- Generated tokens
- Tokens per second
- Model loading time
- CPU/GPU execution
"""


import requests
import json
import time
import csv
from datetime import datetime


# =====================================================
# CONFIGURATION
# =====================================================


OLLAMA_API = "http://localhost:11434/api/generate"


MODELS = [

    "phi4:14b",
    "qwen3.8:27b",
    "gemma4:12b"

]


DEVICES = [

    "GPU",
    "CPU"

]


REPETITIONS = 5


PROMPT = """

Explain the main advantages and challenges of deploying
large language models in decentralized environments.

Provide a concise technical explanation.

"""


NUM_PREDICT = 256


OUTPUT_FILE = "ollama_q1_benchmark_results.csv"



# =====================================================
# OLLAMA OPTIONS
# =====================================================


def get_options(device):


    options = {

        "temperature":0,

        "num_predict":NUM_PREDICT,

        "num_ctx":4096

    }


    if device == "CPU":

        options["num_gpu"] = 0


    return options




# =====================================================
# RUN SINGLE INFERENCE
# =====================================================


def benchmark(model, device):


    payload = {


        "model": model,

        "prompt": PROMPT,

        "stream": True,

        "options": get_options(device)


    }



    start_time = time.time()


    first_token_time = None


    final_data = {}


    response = requests.post(

        OLLAMA_API,

        json=payload,

        stream=True

    )



    for line in response.iter_lines():


        if not line:

            continue


        current_time = time.time()


        data = json.loads(
            line.decode("utf-8")
        )



        # First generated token arrival

        if first_token_time is None:

            if data.get("response"):

                first_token_time = current_time




        # Final Ollama statistics

        if data.get("done"):


            final_data = data



    end_time = time.time()



    # ----------------------------
    # Metrics
    # ----------------------------


    latency = end_time - start_time



    if first_token_time:

        ttft = first_token_time - start_time

    else:

        ttft = None



    # Real tokens generated by Ollama

    tokens = final_data.get(

        "eval_count",

        0

    )



    eval_duration = final_data.get(

        "eval_duration",

        0

    )



    if eval_duration > 0:


        generation_time = eval_duration / 1e9


        tps = tokens / generation_time


    else:

        tps = 0



    load_duration = final_data.get(

        "load_duration",

        0

    ) / 1e9



    prompt_tokens = final_data.get(

        "prompt_eval_count",

        0

    )



    return {


        "model":model,

        "device":device,

        "latency_seconds":latency,

        "ttft_seconds":ttft,

        "generated_tokens":tokens,

        "tokens_per_second":tps,

        "model_load_seconds":load_duration,

        "prompt_tokens":prompt_tokens


    }




# =====================================================
# MAIN
# =====================================================


results=[]



for model in MODELS:


    for device in DEVICES:


        print("\n============================")

        print(model, device)

        print("============================")



        for rep in range(1, REPETITIONS+1):


            print(

                "Run",

                rep,

                "/",

                REPETITIONS

            )



            result = benchmark(

                model,

                device

            )



            result["repetition"] = rep


            result["timestamp"] = datetime.now()



            results.append(result)




# =====================================================
# SAVE RESULTS
# =====================================================


with open(

    OUTPUT_FILE,

    "w",

    newline=""

) as file:


    writer = csv.DictWriter(

        file,

        fieldnames=results[0].keys()

    )


    writer.writeheader()


    writer.writerows(results)



print("\n================================")

print("Benchmark completed")

print(

    "Results saved:",

    OUTPUT_FILE

)

print("================================")